export type EquipmentCategory =
  | 'pumps'
  | 'exchangers'
  | 'columns'
  | 'valves'
  | 'compressors'
  | 'tanks'
  | 'inline';

export interface EquipmentPort {
  id: string;
  type: 'inlet' | 'outlet' | 'vent' | 'drain';
  label: string;
  position: 'top' | 'bottom' | 'left' | 'right';
}

export interface EquipmentAsset {
  id: string;
  tag: string;
  name: string;
  category: EquipmentCategory;
  standard: string;
  subType: string;
  specs: { label: string; value: string }[];
  ports: EquipmentPort[];
  color: string;
  symbol: string; // Identifier for SVG symbol rendering
}

export interface LineSpec {
  id: string;
  label: string;
  size: string;
  service: string;
  serviceCode: string;
  materialClass: string;
  color: string;
  description: string;
}

